# Pass-run statuses that indicate "incomplete" (informational, do not affect clean)
_INCOMPLETE_STATUSES: frozenset[str] = frozenset({
    L3_PASS_RUN_STATUS_PLANNED,
    L3_PASS_RUN_STATUS_SELECTED_NOT_STARTED,
    L3_PASS_RUN_STATUS_RUNNING,
})


def _working_set_staleness_diagnostic(
    *,
    member_refs: list[dict[str, str]],
    member_count: int,
    name: str,
    member_states: list[dict[str, Any]],
) -> dict[str, Any]:
    """Flag superseded prior_products, failed pass_runs, and unresolved members.

    clean := all three flagged category counts == 0 (R12).
    Informational (do not affect clean): incomplete_pass_runs,
    pass_runs_completed_with_warnings.

    Pure function — no IO, no timestamps.
    """
    state_by_key: dict[tuple[str, str], dict[str, Any]] = {
        (s["ref_kind"], s["ref_id"]): s for s in member_states
    }

    superseded_refs: list[str] = []
    failed_pass_run_refs: list[str] = []
    unresolved_refs: list[str] = []
    incomplete_pass_run_count = 0
    completed_with_warnings_count = 0

    for m in member_refs:
        rk = m["ref_kind"]
        rid = m["ref_id"]
        state = state_by_key.get((rk, rid))
        if state is None or not state.get("resolved", False):
            unresolved_refs.append(rid)
            continue
        if rk == "prior_product":
            if state.get("lifecycle_status") == "superseded":
                superseded_refs.append(rid)
        elif rk == "pass_run":
            status = state.get("status", "")
            if status == L3_PASS_RUN_STATUS_FAILED:
                failed_pass_run_refs.append(rid)
            elif status in _INCOMPLETE_STATUSES:
                incomplete_pass_run_count += 1
            elif status == L3_PASS_RUN_STATUS_COMPLETED_WITH_WARNINGS:
                completed_with_warnings_count += 1

    # Sort for determinism before applying caps (order-invariant regardless of member_refs order)
    superseded_refs.sort()
    failed_pass_run_refs.sort()
    unresolved_refs.sort()

    # Cap at _RESULT_LIST_CAP for result_summary lists
    clean = (
        len(superseded_refs) == 0
        and len(failed_pass_run_refs) == 0
        and len(unresolved_refs) == 0
    )

    return {
        "clean": clean,
        "member_count": member_count,
        # Flagged categories (affect clean)
        "superseded_prior_products": {
            "count": len(superseded_refs),
            "members": superseded_refs[:_RESULT_LIST_CAP],
        },
        "failed_pass_runs": {
            "count": len(failed_pass_run_refs),
            "members": failed_pass_run_refs[:_RESULT_LIST_CAP],
        },
        "unresolved_members": {
            "count": len(unresolved_refs),
            "members": unresolved_refs[:_RESULT_LIST_CAP],
        },
        # Informational counts (do not affect clean)
        "incomplete_pass_runs": incomplete_pass_run_count,
        "pass_runs_completed_with_warnings": completed_with_warnings_count,
    }


def _render_title_staleness_diagnostic(method_id: str, *, working_set: L3WorkingSet) -> str:
    return f"Staleness diagnostic: {working_set.name}"


def _render_body_staleness_diagnostic(method_id: str, *, result: dict[str, Any]) -> str:
    clean = result.get("clean", False)
    # Count total flagged issues
    issue_count = (
        result.get("superseded_prior_products", {}).get("count", 0)
        + result.get("failed_pass_runs", {}).get("count", 0)
        + result.get("unresolved_members", {}).get("count", 0)
    )
    if clean:
        verdict = "Staleness verdict: clean"
    else:
        verdict = f"Staleness verdict: stale — {issue_count} issue(s)"

    lines: list[str] = [verdict]

    def _section(label: str, category_key: str) -> None:
        cat = result.get(category_key, {})
        count = cat.get("count", 0)
        if count == 0:
            return
        members = cat.get("members", [])
        shown = members[:_BODY_LIST_CAP]
        remainder = count - len(shown)
        lines.append(f"{label}: {count}")
        for rid in shown:
            lines.append(f"  - {rid}")
        if remainder > 0:
            lines.append(f"  +{remainder} more")

    _section("Superseded prior products", "superseded_prior_products")
    _section("Failed pass runs", "failed_pass_runs")
    _section("Unresolved members", "unresolved_members")

    # Informational counts
    incomplete = result.get("incomplete_pass_runs", 0)
    with_warnings = result.get("pass_runs_completed_with_warnings", 0)
    if incomplete or with_warnings:
        lines.append(f"Incomplete pass runs (informational): {incomplete}")
        lines.append(f"Pass runs completed with warnings (informational): {with_warnings}")

    return "\n".join(lines)


