# Public runner
# ---------------------------------------------------------------------------


def run_method(
    method_id: str,
    *,
    working_set: L3WorkingSet,
    member_states: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    """Run the named deterministic method over the working set.

    Returns a result dict containing method_id, method_version, and the
    computed summary payload.  Raises KeyError if method_id is unknown
    (caller maps this to a Layer3AnalysisProductError).

    For methods with consumes_member_state=True, member_states MUST be
    provided; passing None raises ValueError (fail-closed per R1).

    Deterministic: identical (working_set, member_states) -> identical result.
    """
    spec = DETERMINISTIC_METHODS[method_id]  # KeyError propagates to caller

    if spec.consumes_member_state:
        if member_states is None:
            raise ValueError(
                f"method '{method_id}' requires member_states but None was provided."
            )
        summary = spec.fn(
            member_refs=list(working_set.member_refs_json),
            member_count=working_set.member_count,
            name=working_set.name,
            member_states=member_states,
        )
    else:
        summary = spec.fn(
            member_refs=list(working_set.member_refs_json),
            member_count=working_set.member_count,
            name=working_set.name,
        )

    return {
        "method_id": spec.method_id,
        "method_version": spec.version,
        **summary,
    }


# ---------------------------------------------------------------------------
# Title / body renderers (pure, stable) — thin dispatchers over spec callables
# ---------------------------------------------------------------------------


def render_title(method_id: str, *, working_set: L3WorkingSet) -> str:
    """Return a deterministic, human-readable product title."""
    spec = DETERMINISTIC_METHODS.get(method_id)
    if spec is not None:
        return spec.render_title(method_id, working_set=working_set)
    # Generic fallback for unknown method ids (preserves existing contract)
    return f"Deterministic analysis: {working_set.name} [{method_id}]"


def render_body(method_id: str, *, result: dict[str, Any]) -> str:
    """Return a deterministic, human-readable product body."""
    spec = DETERMINISTIC_METHODS.get(method_id)
    if spec is not None:
        return spec.render_body(method_id, result=result)
    # Generic fallback for unknown method ids (preserves existing contract)
    return f"method_id={result.get('method_id')} method_version={result.get('method_version')}"
