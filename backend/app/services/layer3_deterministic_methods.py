def render_title(method_id: str, *, working_set: L3WorkingSet) -> str:
    """Return a deterministic, human-readable product title."""
    spec = DETERMINISTIC_METHODS.get(method_id)
    if spec is not None:
        return spec.render_title(method_id, working_set=working_set)
    # Generic fallback for unknown method ids (preserves existing contract)
    return f"Deterministic analysis: {working_set.name} [{method_id}]"


