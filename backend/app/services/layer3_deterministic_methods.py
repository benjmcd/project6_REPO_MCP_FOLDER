"""Layer 3 deterministic analysis methods registry.

Pure, server-internal methods that compute over working-set MEMBER METADATA
(ref_kind/ref_id counts and resolved state fields).  No IO, no randomness, no timestamps.
Same input always yields the same result.

executor_type="deterministic" products are generated by
layer3_analysis_product_generation.py which calls run_method() here.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass
from typing import Any, Callable

from app.models.models import (
    L3WorkingSet,
    L3_PASS_RUN_STATUS_COMPLETED_WITH_WARNINGS,
    L3_PASS_RUN_STATUS_FAILED,
    L3_PASS_RUN_STATUS_PLANNED,
    L3_PASS_RUN_STATUS_RUNNING,
    L3_PASS_RUN_STATUS_SELECTED_NOT_STARTED,
)

# ---------------------------------------------------------------------------
# Schema ID
# ---------------------------------------------------------------------------

DETERMINISTIC_METHODS_SCHEMA_ID = "layer3.deterministic_method.v1"

# ---------------------------------------------------------------------------
# Bounding constants (binding per R4)
# ---------------------------------------------------------------------------

# Maximum refs listed in a rendered body section ("+K more" suffix).
_BODY_LIST_CAP = 20
# Maximum ref-id strings stored in result_summary per-category list.
_RESULT_LIST_CAP = 100


# ---------------------------------------------------------------------------
# Internal method spec
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class _MethodSpec:
    method_id: str
    version: int
    fn: Callable[..., dict[str, Any]]
    product_kind: str
    label: str
    description: str
    consumes_member_state: bool
    render_title: Callable[..., str]
    render_body: Callable[..., str]


# ---------------------------------------------------------------------------
# Pure computation functions
# ---------------------------------------------------------------------------


def _working_set_composition_summary(
    *,
    member_refs: list[dict[str, str]],
    member_count: int,
    name: str,
) -> dict[str, Any]:
    """Compute composition statistics over the working set member metadata.

    Accesses only ref_kind values — no raw payload, no external IO.
    """
    by_ref_kind: dict[str, int] = dict(
        Counter(m["ref_kind"] for m in member_refs)
    )
    distinct_ref_kinds: list[str] = sorted(by_ref_kind.keys())
    return {
        "by_ref_kind": by_ref_kind,
        "member_count": member_count,
        "distinct_ref_kinds": distinct_ref_kinds,
    }


def _render_title_composition_summary(method_id: str, *, working_set: L3WorkingSet) -> str:
    return f"Working set composition: {working_set.name}"


def _render_body_composition_summary(method_id: str, *, result: dict[str, Any]) -> str:
    by_ref_kind: dict[str, int] = result.get("by_ref_kind", {})
    member_count: int = result.get("member_count", 0)
    distinct: list[str] = result.get("distinct_ref_kinds", [])
    lines: list[str] = [
        f"Member count: {member_count}",
        f"Distinct ref kinds: {len(distinct)}",
    ]
    for kind in distinct:
        lines.append(f"  {kind}: {by_ref_kind[kind]}")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# working_set_member_state_profile  (v1, product_kind="summary")
# ---------------------------------------------------------------------------


def _working_set_member_state_profile(
    *,
    member_refs: list[dict[str, str]],
    member_count: int,
    name: str,
    member_states: list[dict[str, Any]],
) -> dict[str, Any]:
    """Per-ref-kind rollup of resolved state fields plus an unresolved section.

    Pure function over (member_refs, member_count, name, member_states).
    No IO, no timestamps.
    """
    # Build lookup: (ref_kind, ref_id) -> state dict
    state_by_key: dict[tuple[str, str], dict[str, Any]] = {
        (s["ref_kind"], s["ref_id"]): s for s in member_states
    }

    # Per-kind rollup accumulators
    prior_product_by_lifecycle: Counter[str] = Counter()
    pass_run_by_status: Counter[str] = Counter()
    output_package_by_status: Counter[str] = Counter()
    material_snapshot_by_source_plane: Counter[str] = Counter()
    analysis_set_info: list[dict[str, Any]] = []  # for group/unit count derivation

    by_ref_kind: dict[str, int] = dict(Counter(m["ref_kind"] for m in member_refs))

    unresolved_refs: list[str] = []

    for m in member_refs:
        rk = m["ref_kind"]
        rid = m["ref_id"]
        state = state_by_key.get((rk, rid))
        if state is None or not state.get("resolved", False):
            unresolved_refs.append(rid)
            continue
        if rk == "prior_product":
            prior_product_by_lifecycle[(state.get("lifecycle_status") or "unknown")] += 1
        elif rk == "pass_run":
            pass_run_by_status[(state.get("status") or "unknown")] += 1
        elif rk == "output_package":
            output_package_by_status[(state.get("status") or "unknown")] += 1
        elif rk == "material_snapshot":
            material_snapshot_by_source_plane[(state.get("source_plane") or "unknown")] += 1
        elif rk == "analysis_set":
            analysis_set_info.append(state)

    # analysis_set lens: group/unit counts are resolver-produced integers (R4)
    total_group_refs = sum(s.get("group_count") or 0 for s in analysis_set_info)
    total_unit_refs = sum(s.get("unit_count") or 0 for s in analysis_set_info)
    analysis_set_rollup = {
        "count": len(analysis_set_info),
        "total_group_refs": total_group_refs,
        "total_unit_refs": total_unit_refs,
    }

    # Sort for determinism before applying cap (order-invariant regardless of member_refs order)
    unresolved_refs.sort()
    # Cap unresolved list at _RESULT_LIST_CAP for result_summary
    unresolved_count = len(unresolved_refs)
    unresolved_capped = unresolved_refs[:_RESULT_LIST_CAP]

    return {
        "member_count": member_count,
        "by_ref_kind": by_ref_kind,
        "prior_product": {"by_lifecycle_status": dict(prior_product_by_lifecycle)},
        "pass_run": {"by_status": dict(pass_run_by_status)},
        "output_package": {"by_status": dict(output_package_by_status)},
        "material_snapshot": {"by_source_plane": dict(material_snapshot_by_source_plane)},
        "analysis_set": analysis_set_rollup,
        # PROMINENT unresolved section (R5)
        "unresolved": {
            "count": unresolved_count,
            "refs": unresolved_capped,
        },
    }


def _render_title_member_state_profile(method_id: str, *, working_set: L3WorkingSet) -> str:
    return f"Member state profile: {working_set.name}"


def _render_body_member_state_profile(method_id: str, *, result: dict[str, Any]) -> str:
    lines: list[str] = [
        f"Member count: {result.get('member_count', 0)}",
    ]
    # by_ref_kind rollup
    by_ref_kind = result.get("by_ref_kind", {})
    if by_ref_kind:
        lines.append("Composition by ref kind:")
        for kind in sorted(by_ref_kind):
            lines.append(f"  {kind}: {by_ref_kind[kind]}")

    # per-kind rollup lines (counts only — R4)
    pp = result.get("prior_product", {}).get("by_lifecycle_status", {})
    if pp:
        lines.append("Prior product lifecycle statuses:")
        for k in sorted(pp):
            lines.append(f"  {k}: {pp[k]}")

    pr = result.get("pass_run", {}).get("by_status", {})
    if pr:
        lines.append("Pass run statuses:")
        for k in sorted(pr):
            lines.append(f"  {k}: {pr[k]}")

    op = result.get("output_package", {}).get("by_status", {})
    if op:
        lines.append("Output package statuses:")
        for k in sorted(op):
            lines.append(f"  {k}: {op[k]}")

    ms = result.get("material_snapshot", {}).get("by_source_plane", {})
    if ms:
        lines.append("Material snapshot source planes:")
        for k in sorted(ms):
            lines.append(f"  {k}: {ms[k]}")

    asr = result.get("analysis_set", {})
    if asr.get("count", 0):
        lines.append(
            f"Analysis sets: {asr['count']} "
            f"(group refs: {asr.get('total_group_refs', 0)}, "
            f"unit refs: {asr.get('total_unit_refs', 0)})"
        )

    # PROMINENT unresolved section (R5)
    unresolved = result.get("unresolved", {})
    unresolved_count = unresolved.get("count", 0)
    if unresolved_count > 0:
        refs = unresolved.get("refs", [])
        shown = refs[:_BODY_LIST_CAP]
        remainder = unresolved_count - len(shown)
        lines.append(f"UNRESOLVED members: {unresolved_count}")
        for rid in shown:
            lines.append(f"  - {rid}")
        if remainder > 0:
            lines.append(f"  +{remainder} more")

    return "\n".join(lines)


