def _cap_rollup(counter: Counter, cap: int) -> dict[str, int]:
    """Return an ordered dict of at most *cap* entries from *counter*.

    Selection: top entries by (-count, key) — count descending, key ascending
    (a total order, deterministic under ties).  Counts inside the mapping stay
    exact; only the number of listed keys is capped.
    """
    ordered = sorted(counter.items(), key=lambda kv: (-kv[1], kv[0]))
    return dict(ordered[:cap])


def _working_set_member_state_profile(
    *,
    member_refs: list[dict[str, str]],
    member_count: int,
    name: str,
    member_states: list[dict[str, Any]],
) -> dict[str, Any]:
    """Per-ref-kind rollup of resolved state fields plus an unresolved section.

    Pure function over (member_refs, member_count, name, member_states).
    No IO, no timestamps.
    """
    # Build lookup: (ref_kind, ref_id) -> state dict
    state_by_key: dict[tuple[str, str], dict[str, Any]] = {
        (s["ref_kind"], s["ref_id"]): s for s in member_states
    }

    # Per-kind rollup accumulators
    prior_product_by_lifecycle: Counter[str] = Counter()
    pass_run_by_status: Counter[str] = Counter()
    output_package_by_status: Counter[str] = Counter()
    material_snapshot_by_source_plane: Counter[str] = Counter()
    analysis_set_info: list[dict[str, Any]] = []  # for group/unit count derivation

    by_ref_kind: dict[str, int] = dict(Counter(m["ref_kind"] for m in member_refs))

    unresolved_refs: list[str] = []

    for m in member_refs:
        rk = m["ref_kind"]
        rid = m["ref_id"]
        state = state_by_key.get((rk, rid))
        if state is None or not state.get("resolved", False):
            unresolved_refs.append(rid)
            continue
        if rk == "prior_product":
            prior_product_by_lifecycle[(state.get("lifecycle_status") or "unknown")] += 1
        elif rk == "pass_run":
            pass_run_by_status[(state.get("status") or "unknown")] += 1
        elif rk == "output_package":
            output_package_by_status[(state.get("status") or "unknown")] += 1
        elif rk == "material_snapshot":
            material_snapshot_by_source_plane[(state.get("source_plane") or "unknown")] += 1
        elif rk == "analysis_set":
            analysis_set_info.append(state)

    # analysis_set lens: group/unit counts are resolver-produced integers (R4)
    total_group_refs = sum(s.get("group_count") or 0 for s in analysis_set_info)
    total_unit_refs = sum(s.get("unit_count") or 0 for s in analysis_set_info)
    analysis_set_rollup = {
        "count": len(analysis_set_info),
        "total_group_refs": total_group_refs,
        "total_unit_refs": total_unit_refs,
    }

    # Sort for determinism before applying cap (order-invariant regardless of member_refs order)
    unresolved_refs.sort()
    # Cap unresolved list at _RESULT_LIST_CAP for result_summary
    unresolved_count = len(unresolved_refs)
    unresolved_capped = unresolved_refs[:_RESULT_LIST_CAP]

    return {
        "member_count": member_count,
        "by_ref_kind": by_ref_kind,
        "prior_product": {
            "by_lifecycle_status": _cap_rollup(prior_product_by_lifecycle, _ROLLUP_RESULT_CAP),
            "distinct_lifecycle_status_values": len(prior_product_by_lifecycle),
        },
        "pass_run": {
            "by_status": _cap_rollup(pass_run_by_status, _ROLLUP_RESULT_CAP),
            "distinct_status_values": len(pass_run_by_status),
        },
        "output_package": {
            "by_status": _cap_rollup(output_package_by_status, _ROLLUP_RESULT_CAP),
            "distinct_status_values": len(output_package_by_status),
        },
        "material_snapshot": {
            "by_source_plane": _cap_rollup(material_snapshot_by_source_plane, _ROLLUP_RESULT_CAP),
            "distinct_source_plane_values": len(material_snapshot_by_source_plane),
        },
        "analysis_set": analysis_set_rollup,
        # PROMINENT unresolved section (R5)
        "unresolved": {
            "count": unresolved_count,
            "refs": unresolved_capped,
        },
    }


def _render_title_member_state_profile(method_id: str, *, working_set: L3WorkingSet) -> str:
    return f"Member state profile: {working_set.name}"


def _render_body_member_state_profile(method_id: str, *, result: dict[str, Any]) -> str:
    lines: list[str] = [
        f"Member count: {result.get('member_count', 0)}",
    ]
    # by_ref_kind rollup
    by_ref_kind = result.get("by_ref_kind", {})
    if by_ref_kind:
        lines.append("Composition by ref kind:")
        for kind in sorted(by_ref_kind):
            lines.append(f"  {kind}: {by_ref_kind[kind]}")

    # per-kind rollup lines (counts only — R4)
    def _render_rollup_section(label: str, mapping: dict[str, int], distinct_count: int) -> None:
        if not mapping:
            return
        lines.append(f"{label}:")
        # mapping is already ordered by (-count, key) from _cap_rollup; honour that order
        shown = list(mapping.items())[:_ROLLUP_BODY_CAP]
        for k, v in shown:
            lines.append(f"  {k}: {v}")
        remainder = distinct_count - len(shown)
        if remainder > 0:
            lines.append(f"  +{remainder} more values")

    pp_section = result.get("prior_product", {})
    _render_rollup_section(
        "Prior product lifecycle statuses",
        pp_section.get("by_lifecycle_status", {}),
        pp_section.get("distinct_lifecycle_status_values", len(pp_section.get("by_lifecycle_status", {}))),
    )

    pr_section = result.get("pass_run", {})
    _render_rollup_section(
        "Pass run statuses",
        pr_section.get("by_status", {}),
        pr_section.get("distinct_status_values", len(pr_section.get("by_status", {}))),
    )

    op_section = result.get("output_package", {})
    _render_rollup_section(
        "Output package statuses",
        op_section.get("by_status", {}),
        op_section.get("distinct_status_values", len(op_section.get("by_status", {}))),
    )

    ms_section = result.get("material_snapshot", {})
    _render_rollup_section(
        "Material snapshot source planes",
        ms_section.get("by_source_plane", {}),
        ms_section.get("distinct_source_plane_values", len(ms_section.get("by_source_plane", {}))),
    )

    asr = result.get("analysis_set", {})
    if asr.get("count", 0):
        lines.append(
            f"Analysis sets: {asr['count']} "
            f"(group refs: {asr.get('total_group_refs', 0)}, "
            f"unit refs: {asr.get('total_unit_refs', 0)})"
        )

    # PROMINENT unresolved section (R5)
    unresolved = result.get("unresolved", {})
    unresolved_count = unresolved.get("count", 0)
    if unresolved_count > 0:
        refs = unresolved.get("refs", [])
        shown = refs[:_BODY_LIST_CAP]
        remainder = unresolved_count - len(shown)
        lines.append(f"UNRESOLVED members: {unresolved_count}")
        for rid in shown:
            lines.append(f"  - {rid}")
        if remainder > 0:
            lines.append(f"  +{remainder} more")

    return "\n".join(lines)


