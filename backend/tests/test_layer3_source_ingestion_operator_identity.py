def _make_request(client: TestClient, path: str, payload: dict | None, extra_headers: dict | None = None):
    headers = extra_headers or {}
    if path == _p("/source/intake/upload"):
        return client.post(
            path,
            files={"file": ("test.txt", b"test-content", "text/plain")},
            data={
                "client_request_id": "x",
                "operator_decision": "upload",
                "source_label": "test",
            },
            headers=headers,
        )
    if path in _FILE_RESPONSE_ROUTES or payload is None:
        return client.post(path, json={}, headers=headers)
    return client.post(path, json=payload, headers=headers)


def _build_client(tmp_path, monkeypatch, *, auth_owner: str, trusted_proxy: bool):
    storage_dir = tmp_path / "storage"
    monkeypatch.setattr(settings, "storage_dir", str(storage_dir))
    monkeypatch.setattr(settings, "layer3_external_local_export_dir", str(tmp_path / "ext"))
    monkeypatch.setattr(settings, "layer3_internal_webhook_url", "http://127.0.0.1/wh")
    monkeypatch.setattr(settings, "layer3_internal_webhook_display_name", "test-wh")
    monkeypatch.setattr(settings, "layer3_sec_edgar_live_network_enabled", False)
    monkeypatch.setattr(settings, "auth_owner", auth_owner)
    monkeypatch.setattr(settings, "trusted_proxy_mode", trusted_proxy)
    monkeypatch.setattr(settings, "proxy_identity_header", "X-Forwarded-User")
    monkeypatch.setattr(settings, "proxy_groups_header", "X-Forwarded-Groups")
    bootstrap_storage_tree(storage_dir)
    engine = create_engine(
        "sqlite:///:memory:",
        future=True,
        connect_args={"check_same_thread": False},
        poolclass=StaticPool,
    )
    Base.metadata.create_all(engine)
    SessionLocal = sessionmaker(bind=engine, autocommit=False, autoflush=False, future=True)

    def override():
        db = SessionLocal()
        try:
            yield db
        finally:
            db.close()

    app.dependency_overrides[get_db] = override
    client = TestClient(app)
    return client


