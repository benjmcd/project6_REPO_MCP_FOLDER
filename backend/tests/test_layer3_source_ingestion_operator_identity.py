@pytest.mark.parametrize("path", ALL_POST_ROUTES)
def test_409_sweep_untrusted_proxy(path, client_proxy_untrusted):
    payload = _ROUTE_PAYLOADS.get(path, {})
    resp = _make_request(
        client_proxy_untrusted,
        path,
        payload,
        extra_headers={
            "X-Forwarded-User": _IDENTITY_CANARY,
            "X-Forwarded-Groups": _GROUPS_CANARY,
        },
    )
    assert resp.status_code == 409, f"{path} returned {resp.status_code}: {resp.text[:300]}"
    ct = resp.headers.get("content-type", "")
    assert ct.startswith("application/json"), f"expected application/json, got {ct}"
    body = resp.json()
    assert "untrusted_proxy_identity" in body.get("error_code", ""), body
    body_text = resp.text
    assert _IDENTITY_CANARY not in body_text, f"identity canary leaked in 409 body for {path}"
    assert _GROUPS_CANARY not in body_text, f"groups canary leaked in 409 body for {path}"


